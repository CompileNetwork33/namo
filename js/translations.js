// Global language state (defaults to English on first visit, saved in sessionStorage)
let currentLanguage = (function() {
  try {
    return sessionStorage.getItem('namo_preferred_lang') || 'en';
  } catch (e) {
    return 'en';
  }
})();

function getLanguage() {
  return currentLanguage;
}

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'hi') return;
  currentLanguage = lang;
  try {
    sessionStorage.setItem('namo_preferred_lang', lang);
  } catch (e) {
    // Session storage fallback
  }

  // 1. Update document html lang attribute
  document.documentElement.lang = lang;

  // 2. Update toggle button UI
  document.querySelectorAll('.btn-lang').forEach(btn => {
    btn.classList.remove('is-en', 'is-hi');
    btn.classList.add(lang === 'hi' ? 'is-hi' : 'is-en');
    btn.setAttribute('aria-label', lang === 'en' ? 'Switch to Hindi' : 'Switch to English');
  });

  // 3. Replace all visible elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[key] && translations[key][lang]) {
      // Preserve child icons if any
      const icon = el.querySelector('i');
      if (icon) {
        const iconClone = icon.cloneNode(true);
        // If element text contains icon before or after, keep structure
        const isIconFirst = el.firstElementChild === icon;
        el.textContent = translations[key][lang];
        if (isIconFirst) {
          el.prepend(iconClone);
          el.insertBefore(document.createTextNode(' '), el.childNodes[1]);
        } else {
          el.appendChild(document.createTextNode(' '));
          el.appendChild(iconClone);
        }
      } else {
        el.textContent = translations[key][lang];
      }
    }
  });

  // 4. Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[key] && translations[key][lang]) {
      el.placeholder = translations[key][lang];
    }
  });

  // 5. Update select dropdown option texts with data-i18n-opt
  document.querySelectorAll('option[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[key] && translations[key][lang]) {
      el.textContent = translations[key][lang];
    }
  });
}

function toggleLanguage() {
  const newLang = currentLanguage === 'en' ? 'hi' : 'en';
  setLanguage(newLang);
}

// Auto-initialize when DOM is ready
document.addEventListener('DOMContentLoaded', () => {
  // Bind click handlers to all language toggle buttons
  document.querySelectorAll('.btn-lang').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });

  // Apply current language on load
  setLanguage(currentLanguage);
});

// Expose globally
window.NamoI18n = {
  translations,
  getLanguage,
  setLanguage,
  toggleLanguage
};
